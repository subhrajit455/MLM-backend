const User = require('../models/User');
const Order = require('../models/Order');
const VolumeLedger = require('../models/VolumeLedger');
const WalletTransaction = require('../models/WalletTransaction');
const { Decimal, toDecimal, toDecimal128, toFixed4String } = require('../utils/decimal');
const { runWithTransactionOrFallback } = require('../utils/transactionHelper');

const QUALIFICATION_PV_THRESHOLD = new Decimal('100.0000');

/**
 * Refunds an order and executes full financial & volume clawback:
 * 1. Marks Order status = 'REFUNDED'.
 * 2. Reverses buyer PV and binary ancestors' gv_left / gv_right via VolumeLedger.bulkWrite().
 * 3. Creates offsetting negative CLAWBACK entries in WalletTransaction for every bonus paid on this order.
 */
async function refundOrderAndClawback(orderId) {
  return await runWithTransactionOrFallback(async (session) => {
    const sessionOpts = session ? { session } : {};

    const order = await Order.findById(orderId).session(session);
    if (!order) {
      throw new Error('Order not found.');
    }
    if (order.status === 'REFUNDED') {
      throw new Error(`Order ${order.order_number} has already been refunded.`);
    }

    const buyer = await User.findById(order.buyer_id).session(session);
    if (!buyer) {
      throw new Error('Order buyer not found.');
    }

    const periodId = order.period_id;
    const bvDec = toDecimal(order.bv);
    const negBvDec128 = toDecimal128(bvDec.negated());

    // 1. Update order status
    order.status = 'REFUNDED';
    await order.save(sessionOpts);

    // 2. Reverse PV & Upline Binary GV via single bulkWrite
    const bulkOps = [
      {
        updateOne: {
          filter: { user_id: buyer._id, period_id: periodId },
          update: { $inc: { pv: negBvDec128 } }
        }
      }
    ];

    for (const anc of buyer.placement_ancestors || []) {
      const incField = anc.leg === 'LEFT' ? { gv_left: negBvDec128 } : { gv_right: negBvDec128 };
      bulkOps.push({
        updateOne: {
          filter: { user_id: anc.user_id, period_id: periodId },
          update: { $inc: incField }
        }
      });
    }

    await VolumeLedger.bulkWrite(bulkOps, sessionOpts);

    // Floor any negative PV/GV at 0.0000 if settlement had already swept GV into carry
    const buyerLedger = await VolumeLedger.findOne({
      user_id: buyer._id,
      period_id: periodId
    }).session(session);

    if (buyerLedger && toDecimal(buyerLedger.pv).lt(QUALIFICATION_PV_THRESHOLD)) {
      buyer.is_active = false;
      await buyer.save(sessionOpts);
    }

    // 3. Find all original commissions generated by this order and create negative CLAWBACK ledger entries
    const originalTxs = await WalletTransaction.find({
      source_order_id: order._id,
      tx_type: { $in: ['DIRECT_BONUS', 'UNILEVEL_BONUS'] }
    })
      .populate('user_id', 'username full_name')
      .session(session);

    const clawbackEntries = [];

    for (const origTx of originalTxs) {
      const origAmount = toDecimal(origTx.amount);
      const negAmount = origAmount.negated();
      const clawbackKey = `CLAWBACK_${origTx.idempotency_key}`;

      const clawbackTx = await WalletTransaction.findOneAndUpdate(
        { idempotency_key: clawbackKey },
        {
          $setOnInsert: {
            idempotency_key: clawbackKey,
            user_id: origTx.user_id._id || origTx.user_id,
            source_order_id: order._id,
            period_id: periodId,
            tx_type: 'CLAWBACK',
            amount: toDecimal128(negAmount),
            status: 'CLEARED',
            description: `Clawback reversal for refunded order ${order.order_number} (${origTx.tx_type})`,
            metadata: {
              reversed_tx_id: origTx._id.toString(),
              reversed_idempotency_key: origTx.idempotency_key,
              original_tx_type: origTx.tx_type,
              buyer_username: buyer.username,
              refunded_bv: toFixed4String(bvDec)
            }
          }
        },
        { upsert: true, new: true, ...sessionOpts }
      );

      clawbackEntries.push({
        user_id: (origTx.user_id._id || origTx.user_id).toString(),
        username: origTx.user_id.username || 'Distributor',
        original_type: origTx.tx_type,
        clawback_amount: toFixed4String(negAmount),
        idempotency_key: clawbackKey,
        tx_id: clawbackTx._id.toString()
      });
    }

    return {
      order_id: order._id.toString(),
      order_number: order.order_number,
      buyer_username: buyer.username,
      refunded_bv: toFixed4String(bvDec),
      clawbacks_created: clawbackEntries.length,
      clawbacks: clawbackEntries
    };
  });
}

module.exports = {
  refundOrderAndClawback
};

